// Signs that aren't emoji: arrows, math, currency, typography, the keyboard, Greek
// letters, fractions, and check marks. A named HTML entity is kept when one exists.

export interface SymbolEntry {
  char: string;
  name: string;
  group: string;
  /** A named HTML entity (`&mdash;`), when the character has one. */
  entity?: string;
  keywords: string[];
}

function entries(group: string, rows: Array<[string, string, string?, string[]?]>): SymbolEntry[] {
  return rows.map(([char, name, entity, keywords]) => ({
    char,
    name,
    group,
    ...(entity ? { entity } : {}),
    keywords: keywords ?? [],
  }));
}

